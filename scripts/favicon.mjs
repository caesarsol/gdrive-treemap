// Writes assets/favicon.svg: the logo's tiles filling the icon, with no glow. The gaps between
// tiles stay at least 2px wide whatever size the icon is drawn at: the SVG carries one layout per
// size band and media queries (evaluated against the size the icon is drawn at) pick one.
//   node scripts/favicon.mjs
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const SIDE = 76;
const COLORS = { big: '#66bfff', top: '#30d158', yellow: '#ffd60a', pink: '#ff99c4', orange: '#ff9f0a' };

/** The logo's layout with gap `g`: with g = 2 it is exactly the logo's 44/30 × 40/34 … split. */
function layout(g) {
  const bigW = ((SIDE - g) * 44) / 74;
  const right = SIDE - g - bigW;
  const topH = ((SIDE - g) * 40) / 74;
  const bottomH = SIDE - g - topH;
  const yellowW = ((right - g) * 16) / 28;
  const smallW = right - g - yellowW;
  const pinkH = ((bottomH - g) * 18) / 32;
  const x2 = bigW + g, y2 = topH + g, x3 = x2 + yellowW + g;
  return [
    ['big', 0, 0, bigW, SIDE],
    ['top', x2, 0, right, topH],
    ['yellow', x2, y2, yellowW, bottomH],
    ['pink', x3, y2, smallW, pinkH],
    ['orange', x3, y2 + pinkH + g, smallW, bottomH - pinkH - g],
  ];
}

// Size bands (px, up to and including). Each band's gap is 2px at its smallest size, so more above
// it; the first band is sized for 16px, the smallest favicon.
const BANDS = [16, 24, 32, 48, 76, Infinity];
const fmt = (n) => +n.toFixed(2);
const groups = BANDS.map((_, i) => {
  const smallest = i === 0 ? 16 : BANDS[i - 1];
  const g = Math.max(2, (2 * SIDE) / smallest);
  const rects = layout(g).map(([k, x, y, w, h]) =>
    `<rect x="${fmt(x)}" y="${fmt(y)}" width="${fmt(w)}" height="${fmt(h)}" fill="${COLORS[k]}"/>`);
  return `  <g class="b${i}">\n    ${rects.join('\n    ')}\n  </g>`;
});
const min = (i) => (i === 0 ? 0 : BANDS[i - 1] + 0.01);
const css = BANDS.map((max, i) => {
  const query = [i > 0 && `(min-width: ${min(i)}px)`, max !== Infinity && `(max-width: ${max}px)`].filter(Boolean).join(' and ');
  return `    @media ${query} { .b${i} { display: inline; } }`;
});

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SIDE} ${SIDE}">
  <!-- Generated by scripts/favicon.mjs: the logo's tiles, with gaps of at least 2px at any size. -->
  <style>
    g { display: none; }
${css.join('\n')}
  </style>
${groups.join('\n')}
</svg>
`;
writeFileSync(resolve(import.meta.dirname, '../assets/favicon.svg'), svg);
